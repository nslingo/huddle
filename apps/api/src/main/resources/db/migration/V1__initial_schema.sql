    CONSTRAINT fk_saved_clubs_club
        FOREIGN KEY (club_id) REFERENCES clubs (id) ON DELETE CASCADE
);

CREATE INDEX idx_saved_clubs_club ON saved_clubs (club_id);

-- ---------------------------------------------------------------------------
