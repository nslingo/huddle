-- ---------------------------------------------------------------------------
-- instagram_posts
-- ---------------------------------------------------------------------------
CREATE TABLE instagram_posts (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    club_id       bigint         NOT NULL,
    ig_post_id    text           NOT NULL UNIQUE,
    permalink     text           NOT NULL,
    like_count    int            NOT NULL,
    comment_count int            NOT NULL,
    caption       text,
    media_type    post_media_type NOT NULL,
    media_url     text           NOT NULL,
    thumbnail_url text,
    posted_at     timestamptz    NOT NULL,
    scraped_at    timestamptz    NOT NULL DEFAULT now(),
    CONSTRAINT fk_instagram_posts_club
        FOREIGN KEY (club_id) REFERENCES clubs (id) ON DELETE CASCADE,
    CONSTRAINT ck_instagram_posts_permalink_nonempty CHECK (length(btrim(permalink)) > 0),
    CONSTRAINT ck_instagram_posts_like_count    CHECK (like_count >= 0),
    CONSTRAINT ck_instagram_posts_comment_count CHECK (comment_count >= 0),
    CONSTRAINT ck_instagram_posts_media_url_nonempty CHECK (length(btrim(media_url)) > 0)
);

CREATE INDEX idx_instagram_posts_club_posted ON instagram_posts (club_id, posted_at);

-- ---------------------------------------------------------------------------
-- events
-- ---------------------------------------------------------------------------
CREATE TABLE events (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id             uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    club_id               bigint       NOT NULL,
    title                 text         NOT NULL,
    description           text,
    starts_at             timestamptz  NOT NULL,
    ends_at               timestamptz,
    location              text,
    source                event_source NOT NULL DEFAULT 'instagram',
    source_post_id        bigint,
    extraction_confidence real,
    event_key             text         NOT NULL UNIQUE,
    created_at            timestamptz  NOT NULL DEFAULT now(),
    updated_at            timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT fk_events_club
        FOREIGN KEY (club_id) REFERENCES clubs (id) ON DELETE CASCADE,
    CONSTRAINT fk_events_source_post
        FOREIGN KEY (source_post_id) REFERENCES instagram_posts (id) ON DELETE SET NULL,
    CONSTRAINT ck_events_title_nonempty   CHECK (length(btrim(title)) > 0),
    CONSTRAINT ck_events_ends_after_start CHECK (ends_at IS NULL OR ends_at >= starts_at),
    CONSTRAINT ck_events_confidence_range CHECK (extraction_confidence BETWEEN 0 AND 1),
    CONSTRAINT ck_events_key_nonempty     CHECK (length(btrim(event_key)) > 0)
);

CREATE INDEX idx_events_club_starts ON events (club_id, starts_at);
CREATE INDEX idx_events_starts      ON events (starts_at);
CREATE INDEX idx_events_source_post ON events (source_post_id);

CREATE TRIGGER trg_events_set_updated_at
    BEFORE UPDATE ON events
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------------------
-- scrape_runs
-- ---------------------------------------------------------------------------
CREATE TABLE scrape_runs (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    club_id     bigint        NOT NULL,
    status      scrape_status NOT NULL,
    started_at  timestamptz   NOT NULL DEFAULT now(),
    finished_at timestamptz,
    posts_found int           NOT NULL DEFAULT 0,
    posts_new   int           NOT NULL DEFAULT 0,
    error       text,
    CONSTRAINT fk_scrape_runs_club
        FOREIGN KEY (club_id) REFERENCES clubs (id) ON DELETE CASCADE,
    CONSTRAINT ck_scrape_runs_finished_time CHECK (finished_at IS NULL OR finished_at >= started_at),
    CONSTRAINT ck_scrape_runs_posts_found   CHECK (posts_found >= 0),
    CONSTRAINT ck_scrape_runs_posts_new     CHECK (posts_new >= 0 AND posts_new <= posts_found)
);

CREATE INDEX idx_scrape_runs_club_started ON scrape_runs (club_id, started_at);
CREATE INDEX idx_scrape_runs_status       ON scrape_runs (status);